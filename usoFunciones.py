import math

num = float(input("Ingrese un numero: "))

seno = math.sin(num)
coseno = math.cos(num)
tangente = math.tan(num)
raizCuadrada = math.sqrt(num)
logaritmoNatural = math.log(num)
logaritmo10 = math.log10(num)

print("El valor del seno es:", seno)
print("El valor del coseno es:", coseno)
print("El valor de tangente es:", tangente)
print("El valor de raiz cuadrada es:", raizCuadrada)
print("El valor de logaritmo natural es:", logaritmoNatural)
print("El valor de logaritmo10 es:", logaritmo10)