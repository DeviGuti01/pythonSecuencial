Nota1 = float(input("Ingrese su primer valor de la Nota: "))

Nota2 = float(input("Ingrese su segundo valor de la Nota: "))

Nota3 = float(input("Ingrese su tercer valor de la Nota: "))

Nota4 = float(input("Ingrese su cuarto valor de la Nota: "))

